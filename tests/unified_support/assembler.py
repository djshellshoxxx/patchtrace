"""Small label-aware x86-64 encoder for synthetic byte fixtures only.

UNVERIFIED: encodings have been traced by hand but not decoded by an independent tool.
Registers are the volatile low-bank RAX/RCX/RDX/R8 are deliberately not mixed: only RAX, RCX, RDX,
RBX, RSI and RDI are accepted. RSP/RBP and extended registers are excluded to keep encodings explicit.
No generated byte string is executable test code.
"""
from __future__ import annotations

import struct
from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field

REGISTERS = {"rax": 0, "rcx": 1, "rdx": 2, "rbx": 3, "rsi": 6, "rdi": 7}
CONDITIONS = {"o": 0, "no": 1, "b": 2, "ae": 3, "e": 4, "ne": 5, "be": 6, "a": 7,
              "s": 8, "ns": 9, "p": 10, "np": 11, "l": 12, "ge": 13, "le": 14, "g": 15}


def _reg(name: str) -> int:
    if name not in REGISTERS:
        raise ValueError(f"unsupported register {name}")
    return REGISTERS[name]


def _i32(value: int) -> bytes:
    if type(value) is not int or not -(2**31) <= value < 2**31:
        raise ValueError("signed displacement or immediate out of range")
    return struct.pack("<i", value)


@dataclass
class Assembler:
    """Rel32 branches and RIP-relative LEA resolve after layout; all operands are authored fixture data."""

    data: bytearray = field(default_factory=bytearray)
    labels: dict[str, int] = field(default_factory=dict)
    fixups: list[tuple[int, str, int | None]] = field(default_factory=list)

    def label(self, name: str) -> Assembler:
        if not name or name in self.labels:
            raise ValueError("empty or duplicate label")
        self.labels[name] = len(self.data)
        return self

    def mov(self, destination: str, source: int | str) -> Assembler:
        register = _reg(destination)
        if isinstance(source, str):
            self.data.extend(bytes((0x48, 0x89, 0xc0 | (_reg(source) << 3) | register)))
        else:
            if type(source) is not int or not 0 <= source < 2**64:
                raise ValueError("mov immediate out of range")
            self.data.extend(bytes((0x48, 0xb8 + register)) + struct.pack("<Q", source))
        return self

    def _arithmetic(self, destination: str, source: int | str, opcode: int, group: int) -> Assembler:
        register = _reg(destination)
        if isinstance(source, str):
            self.data.extend(bytes((0x48, opcode, 0xc0 | (_reg(source) << 3) | register)))
        else:
            self.data.extend(bytes((0x48, 0x81, 0xc0 | (group << 3) | register)) + _i32(source))
        return self

    def add(self, destination: str, source: int | str) -> Assembler:
        return self._arithmetic(destination, source, 0x01, 0)

    def cmp(self, destination: str, source: int | str) -> Assembler:
        return self._arithmetic(destination, source, 0x39, 7)

    def _relative(self, prefix: bytes, target: str) -> Assembler:
        self.data.extend(prefix)
        offset = len(self.data)
        self.data.extend(b"\0" * 4)
        self.fixups.append((offset, target, None))
        return self

    def call(self, target: str) -> Assembler:
        return self._relative(b"\xe8", target)

    def jmp(self, target: str) -> Assembler:
        return self._relative(b"\xe9", target)

    def jcc(self, condition: str, target: str) -> Assembler:
        if condition not in CONDITIONS:
            raise ValueError("unknown condition")
        return self._relative(bytes((0x0f, 0x80 + CONDITIONS[condition])), target)

    def lea(self, destination: str, target: str) -> Assembler:
        return self._relative(bytes((0x48, 0x8d, 0x05 | (_reg(destination) << 3))), target)

    def ret(self) -> Assembler:
        self.data.append(0xc3)
        return self

    def nop(self, count: int = 1) -> Assembler:
        if type(count) is not int or not 0 <= count <= 65536:
            raise ValueError("nop count out of range")
        self.data.extend(b"\x90" * count)
        return self

    def thunk(self, target: str) -> Assembler:
        return self.jmp(target)

    def switch(self, table: str) -> Assembler:
        """RAX is an already bounded index; table stores signed offsets relative to its own start.

        LEA RDX,[RIP+table]; MOVSXD RAX,[RDX+RAX*4]; ADD RAX,RDX; JMP RAX.
        Index validation belongs to the authored caller, never inferred from these bytes.
        """
        self.lea("rdx", table)
        self.data.extend(bytes.fromhex("486304824801d0ffe0"))
        return self

    def jump_table(self, targets: Sequence[str]) -> Assembler:
        if not 1 <= len(targets) <= 256:
            raise ValueError("jump table size out of range")
        table_offset = len(self.data)
        for target in targets:
            offset = len(self.data)
            self.data.extend(b"\0" * 4)
            self.fixups.append((offset, target, table_offset))
        return self

    def assemble(self, rva: int, symbols: Mapping[str, int] | None = None) -> bytes:
        if type(rva) is not int or not 0 <= rva < 2**32:
            raise ValueError("RVA out of range")
        external = dict(symbols or {})
        if self.labels.keys() & external.keys():
            raise ValueError("duplicate local and external symbol")
        addresses = external | {name: rva + off for name, off in self.labels.items()}
        out = bytearray(self.data)
        for offset, name, table_offset in self.fixups:
            if name not in addresses:
                raise ValueError(f"unresolved symbol {name}")
            origin = rva + (offset + 4 if table_offset is None else table_offset)
            out[offset:offset + 4] = _i32(addresses[name] - origin)
        return bytes(out)
