from kev_helpers import document, entry, render, parse_bytes, ABSENT
from patchtrace.kev.contracts import KevError
def t(label, doc=None, raw=None):
    try:
        c = parse_bytes(raw if raw is not None else render(doc))
        e = c.entries[0]
        print(f'{label:34} ACCEPTED  warnings={len(c.meta.warnings)} e0.name={e.name!r:.30} added={e.date_added} due={e.due_date}')
    except KevError as ex: print(f'{label:34} rejected {ex.code}')
    except BaseException as ex: print(f'{label:34} !!! CRASH {type(ex).__name__}: {str(ex)[:80]}')
t('baseline', document())
t('empty vendor/product/name', document([entry(1, vendorProject='', product='', vulnerabilityName='')]))
t('whitespace-only name', document([entry(1, vulnerabilityName='  ​ ')]))
t('dateAdded after dateReleased', document([entry(1, dateAdded='2099-01-01', dueDate='2099-02-01')]))
t('leap day 2023-02-29 added', document([entry(1, dateAdded='2023-02-29', dueDate='2023-03-29')]))
t('leap day release 2024-02-29', document(dateReleased='2024-02-29T23:59:59Z'))
t('leap second 23:59:60', document(dateReleased='2024-02-29T23:59:60Z'))
t('release 24:00:00', document(dateReleased='2024-02-29T24:00:00Z'))
t('release with +00:00', document(dateReleased='2024-02-29T10:00:00+00:00'))
t('release lower z', document(dateReleased='2024-02-29T10:00:00z'))
