t('surrogate in unknown field name', raw=b'{"catalogVersion":"1","dateReleased":"2024-02-29T10:00:00Z","count":1,"\\ud800k":1,"vulnerabilities":[{"cveID":"CVE-2024-0001","vendorProject":"a","product":"b","vulnerabilityName":"n","dateAdded":"2024-01-01","shortDescription":"d","requiredAction":"r","dueDate":"2024-01-02","\\udc00z":3}]}')
