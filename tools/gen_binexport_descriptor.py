"""Regenerate `src/patchtrace/secondary/binexport_descriptor.py` from the pinned binexport2.proto (SPEC-10b §2.3).

usage: gen_binexport_descriptor.py PATH/TO/binexport2.proto [--protoc PATH] [--check]

The .proto must be byte-identical to google/binexport@2bff7af (SHA-256 checked). The descriptor set is produced
by a local `protoc` (``--protoc``) or, when importable, by ``grpc_tools`` (neither is a runtime or dev
dependency; install them in a throwaway environment). ``--check`` compares instead of writing (exit 1 on drift).
Source info is not included, so the output depends only on the .proto text, not on the protoc version.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import subprocess
import sys
import tempfile
import textwrap
from pathlib import Path

PROTO_SHA256 = 'e8e4943de00b37038b614bbd0515cb188caf3e4a2e20c6566544e791f93647d8'
PROTO_COMMIT = '2bff7af27af206354b2a90a9de566dc6bbae3e1b'
TARGET = Path(__file__).resolve().parents[1] / 'src' / 'patchtrace' / 'secondary' / 'binexport_descriptor.py'


def descriptor_set(proto: Path, protoc: str | None) -> tuple[bytes, str]:
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / 'bx.desc'
        args = [f'-I{proto.parent}', f'--descriptor_set_out={out}', proto.name]
        if protoc:
            version = subprocess.run([protoc, '--version'], capture_output=True, text=True, check=True).stdout
            subprocess.run([protoc, *args], check=True, cwd=proto.parent)
            tool = version.strip()
        else:
            import importlib.metadata

            from grpc_tools import _protoc_compiler  # type: ignore[import-not-found]
            code = _protoc_compiler.run_main([b'protoc', *[a.encode() for a in args]])
            if code:
                raise SystemExit(f'grpc_tools protoc failed with {code}')
            tool = f'grpcio-tools {importlib.metadata.version("grpcio-tools")}'
        return out.read_bytes(), tool


def render(data: bytes, tool: str) -> str:
    b64 = base64.b64encode(data).decode('ascii')
    lines = '\n'.join(f'    {chunk!r}' for chunk in textwrap.wrap(b64, 100))
    return (
        '"""GENERATED by tools/gen_binexport_descriptor.py - do not edit (SPEC-10b §2.3).\n\n'
        'FileDescriptorSet of google/binexport binexport2.proto (Apache-2.0, see\n'
        'third_party/notices/binexport-2bff7af). Constants only, no logic.\n"""\n'
        f'PROTO_SHA256 = {PROTO_SHA256!r}\n'
        f'PROTO_COMMIT = {PROTO_COMMIT!r}\n'
        f'GENERATOR = {tool!r}\n'
        f'DESCRIPTOR_SET_SHA256 = {hashlib.sha256(data).hexdigest()!r}\n'
        f'DESCRIPTOR_SET_B64 = (\n{lines}\n)\n')


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('proto', type=Path)
    parser.add_argument('--protoc')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    if hashlib.sha256(args.proto.read_bytes()).hexdigest() != PROTO_SHA256:
        print('binexport2.proto does not match the pinned SHA-256', file=sys.stderr)
        return 1
    data, tool = descriptor_set(args.proto.resolve(), args.protoc)
    if args.check:
        from patchtrace.secondary import binexport_descriptor as current
        same = base64.b64decode(''.join(current.DESCRIPTOR_SET_B64)) == data
        print('descriptor up to date' if same else 'descriptor DRIFT')
        return 0 if same else 1
    TARGET.write_text(render(data, tool), encoding='utf-8')
    print(f'wrote {TARGET} ({len(data)} bytes descriptor)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
