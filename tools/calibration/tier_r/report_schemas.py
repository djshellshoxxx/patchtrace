"""Schemas and examples for the SPEC-32 s10 evaluation outputs (`tier-r-engine-output/1`, plus the `tier-r-report/1` example
produced by the real evaluator on SYNTHETIC engine output). Kept apart from `schemas.py` (the contracts' owner): the
`tier-r-report/1` model itself lives in `contracts.py` and is generated by `schemas.py`; this file generates the schema of
the normalised per-pair engine output that `output_sha256` in a report pair row hashes, into `docs/schemas/corpus/`, and the
report examples into `docs/schemas/corpus/report-examples/` (a separate folder: `schemas.examples()` owns `examples/`).

Run from the repository root: `PYTHONPATH=src python -m tools.calibration.tier_r.report_schemas` (or the `schemas` CLI verb).
"""
from __future__ import annotations

import copy
import hashlib
import json
from collections.abc import Callable
from pathlib import Path
from typing import Annotated, Literal

from pydantic import BaseModel, ConfigDict, Field, ValidationError

from ..common import canonical_json, digest, strict_json
from . import contracts as C

OUT = Path('docs/schemas/corpus')
EXAMPLES = 'report-examples'
OUTPUT_CONTRACT = 'tier-r-engine-output/1'
MAX_PREDICTIONS = 1_000_000


class _Strict(BaseModel):
    model_config = ConfigDict(extra='forbid', strict=True, frozen=True)


class PredictionDoc(_Strict):
    old_rva: C.Rva
    new_rva: C.Rva
    changed: bool
    similarity_milli: int | None = Field(default=None, ge=0, le=1000)
    old_name: str | None = Field(default=None, max_length=512)
    new_name: str | None = Field(default=None, max_length=512)


class EngineOutputDoc(_Strict):
    """One engine's answer for one pair, reduced to RVAs: the only thing the scorer reads."""
    contract: Literal['tier-r-engine-output/1']
    engine: Literal['rz-diff', 'bindiff', 'ghidriff']
    version: str | None = Field(default=None, max_length=200)
    symbols: Literal['hidden', 'visible']
    older_sha256: C.Sha256
    newer_sha256: C.Sha256
    implicit_unchanged: bool = False
    predictions: tuple[PredictionDoc, ...] = Field(max_length=MAX_PREDICTIONS)
    old_only_rvas: tuple[Annotated[int, Field(ge=0, le=2**32 - 1)], ...] = Field(default=(), max_length=MAX_PREDICTIONS)
    new_only_rvas: tuple[Annotated[int, Field(ge=0, le=2**32 - 1)], ...] = Field(default=(), max_length=MAX_PREDICTIONS)
    ignored_unaddressed: int = Field(default=0, ge=0)


def load_engine_output(data: bytes) -> EngineOutputDoc:
    try:
        strict_json(data)
        return EngineOutputDoc.model_validate_json(data)
    except (ValidationError, ValueError) as exc:
        raise C.ContractError(f'engine output invalid: {str(exc)[:300]}') from None


def output_sha256(doc: dict) -> str:
    return hashlib.sha256(canonical_json(doc)).hexdigest()


SCHEMAS = ((EngineOutputDoc, OUTPUT_CONTRACT),)


def render() -> dict[str, str]:
    out = {}
    for model, ident in SCHEMAS:
        schema = model.model_json_schema()
        schema['$id'] = f'https://patchtrace.local/schemas/{ident}/{model.__name__}.json'
        schema['$schema'] = 'https://json-schema.org/draft/2020-12/schema'
        out[f'{model.__name__}.json'] = json.dumps(schema, indent=2, sort_keys=True) + '\n'
    return out


_A, _B = hashlib.sha256(b'report-example-older').hexdigest(), hashlib.sha256(b'report-example-newer').hexdigest()


def example_engine_output() -> dict:
    return {'contract': OUTPUT_CONTRACT, 'engine': 'rz-diff', 'version': '0.9.1', 'symbols': 'hidden',
            'older_sha256': _A, 'newer_sha256': _B, 'implicit_unchanged': False,
            'predictions': [
                {'old_rva': 0x1000, 'new_rva': 0x1000, 'changed': False, 'similarity_milli': 1000,
                 'old_name': 'fcn.180001000', 'new_name': 'fcn.180001000'},
                {'old_rva': 0x1010, 'new_rva': 0x1010, 'changed': True, 'similarity_milli': 874,
                 'old_name': None, 'new_name': None}],
            'old_only_rvas': [0x1040], 'new_only_rvas': [0x1050], 'ignored_unaddressed': 0}


def example_report() -> dict:
    """The real evaluator on hand-made SYNTHETIC engine output over the template labels: never live evidence."""
    from . import evaluate as E
    from .schemas import example_labels
    labels = C.load_labels(C.dump_json(example_labels()))
    out = E.EngineOutput(
        engine='rz-diff', status='ok', version='0.9.1',
        predictions=(E.Prediction(0x1000, 0x1000, False, 1000), E.Prediction(0x1010, 0x1010, True, 874),
                     E.Prediction(0x1020, 0x1030, True, 990)),
        old_only=frozenset({0x1040}), new_only=frozenset({0x1050}))
    provider = E.StaticProvider('rz-diff', {labels.pair_id: out})
    return E.evaluate([labels], [provider], symbols='hidden',
                      notes=('SYNTHETIC example: mocked engine output, not live evidence',))


def _invalid(base: dict, mutate: Callable[[dict], None], *, redigest: bool = False) -> dict:
    doc = copy.deepcopy(base)
    mutate(doc)
    if redigest:
        doc['report_sha256'] = digest(doc, 'report_sha256')
    return doc


def examples() -> dict[str, dict]:
    report, output = example_report(), example_engine_output()
    return {
        'valid-report-synthetic.json': report,
        'valid-engine-output-rz-diff.json': output,
        'invalid-report-metric-negative.json': _invalid(
            report, lambda d: d['strata']['authored']['rz-diff'].update(identity_tp=-1), redigest=True),
        'invalid-report-unknown-engine.json': _invalid(
            report, lambda d: d['engines'][0].update(engine='ida'), redigest=True),
        'invalid-engine-output-rva-range.json': _invalid(
            output, lambda d: d['predictions'][0].update(old_rva=2**32)),
        'invalid-engine-output-unknown-field.json': _invalid(output, lambda d: d.update(raw_stdout='[]')),
    }


def check_example(path: Path) -> tuple[bool, str]:
    kind = path.name.split('-')[1]
    try:
        {'report': C.load_report, 'engine': load_engine_output}[kind](path.read_bytes())
    except C.ContractError as exc:
        return False, str(exc)[:300]
    return True, 'ok'


def write_all(root: Path = OUT) -> list[Path]:
    root.mkdir(parents=True, exist_ok=True)
    written = []
    for name, text in render().items():
        (root / name).write_text(text, encoding='utf-8', newline='\n')
        written.append(root / name)
    folder = root / EXAMPLES
    folder.mkdir(exist_ok=True)
    for name, doc in examples().items():
        (folder / name).write_bytes(C.dump_json(doc))
        written.append(folder / name)
    return written


def main() -> int:
    for path in write_all():
        print(path.as_posix())
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
