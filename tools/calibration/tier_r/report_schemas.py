"""Schemas and examples for the SPEC-32 s10 evaluation outputs (`tier-r-engine-output/1`, plus the `tier-r-report/1` example
produced by the real evaluator on SYNTHETIC engine output). Kept apart from `schemas.py` (the contracts' owner): the
`tier-r-report/1` model itself lives in `contracts.py` and is generated by `schemas.py`; this file generates the schema of
the normalised per-pair engine output that `output_sha256` in a report pair row hashes, into `docs/schemas/corpus/`, and the
report examples into `docs/schemas/corpus/report-examples/` (a separate folder: `schemas.examples()` owns `examples/`).

Run from the repository root: `PYTHONPATH=src python -m tools.calibration.tier_r.report_schemas` (or the `schemas` CLI verb).
"""
from __future__ import annotations

import copy
import hashlib
import json
from collections.abc import Callable
from pathlib import Path
from typing import Annotated, Literal

from pydantic import BaseModel, ConfigDict, Field, ValidationError, model_validator

from ..common import canonical_json, digest, strict_json
from ..evalcore.engines import common as EC
from . import contracts as C

OUT = Path('docs/schemas/corpus')
EXAMPLES = 'report-examples'
OUTPUT_CONTRACT = 'tier-r-engine-output/1'
CREDITS_CONTRACT = 'tier-r-output-credits/1'
MAX_PREDICTIONS = 1_000_000
MAX_OUTPUT_BYTES = 64 * 1024 * 1024
MAX_CREDIT_BYTES = 64 * 1024 * 1024
FAILURE_CONTRACT = 'tier-r-evaluation-failure/1'
COMPLETION_CONTRACT = 'tier-r-output-completion/1'
Engine = Literal['rz-diff', 'bindiff', 'ghidriff', 'attention']
OrderKeyPart = int | Annotated[float, Field(allow_inf_nan=False)] | Annotated[str, Field(max_length=512)]


class _Strict(BaseModel):
    model_config = ConfigDict(extra='forbid', strict=True, frozen=True)


class PredictionDoc(_Strict):
    old_rva: C.Rva
    new_rva: C.Rva
    changed: bool
    similarity_milli: int | None = Field(default=None, ge=0, le=1000)
    old_name: str | None = Field(default=None, max_length=512)
    new_name: str | None = Field(default=None, max_length=512)
    order_key: tuple[OrderKeyPart, ...] | None = Field(default=None, max_length=16)


class EngineOutputDoc(_Strict):
    """One engine's answer for one pair, reduced to RVAs: the only thing the scorer reads."""
    contract: Literal['tier-r-engine-output/1']
    engine: Engine
    version: str | None = Field(default=None, max_length=200)
    symbols: Literal['hidden', 'visible']
    older_sha256: C.Sha256
    newer_sha256: C.Sha256
    implicit_unchanged: bool = False
    predictions: tuple[PredictionDoc, ...] = Field(max_length=MAX_PREDICTIONS)
    old_only_rvas: tuple[Annotated[int, Field(ge=0, le=2**32 - 1)], ...] = Field(default=(), max_length=MAX_PREDICTIONS)
    new_only_rvas: tuple[Annotated[int, Field(ge=0, le=2**32 - 1)], ...] = Field(default=(), max_length=MAX_PREDICTIONS)
    ignored_unaddressed: int = Field(default=0, ge=0)

    @model_validator(mode='after')
    def comparable_ranking(self):
        """Validate the actual deduplicated scorer keys, including absent-key fallback, without changing them."""
        pairs = EC.to_engine_pairs(engine_output_from_doc(self), self.symbols)
        try:
            sorted(row.order_key for row in pairs.pairs if row.flag)
        except TypeError:
            raise ValueError('effective flagged ordering keys are not mutually comparable') from None
        return self


def engine_output_from_doc(doc: EngineOutputDoc) -> EC.EngineOutput:
    """Reconstruct every producer field used by existing scoring/replay, including optional ranking keys."""
    predictions = tuple(EC.Prediction(p.old_rva, p.new_rva, p.changed, p.similarity_milli,
                                     p.old_name, p.new_name, p.order_key) for p in doc.predictions)
    return EC.EngineOutput(doc.engine, 'ok', version=doc.version, predictions=predictions,
                           old_only=frozenset(doc.old_only_rvas), new_only=frozenset(doc.new_only_rvas),
                           implicit_unchanged=doc.implicit_unchanged, ignored_unaddressed=doc.ignored_unaddressed)


class _InMemoryEngineOutputDoc(EngineOutputDoc):
    """Existing evaluator vocabulary, never a persisted output/credit wire contract."""
    engine: C.Engine


def _validate_output_document(document: dict, model: type[EngineOutputDoc]) -> EngineOutputDoc:
    """Check bounded Python input before encoding; normalize only JSON arrays, never scalar values/defaults."""
    try:
        if not isinstance(document, dict) or set(document) - EngineOutputDoc.model_fields.keys():
            raise ValueError('expected an engine-output object with known fields')
        data = dict(document)
        for field in ('predictions', 'old_only_rvas', 'new_only_rvas'):
            if field not in data:
                continue
            rows = data[field]
            if not isinstance(rows, list | tuple) or len(rows) > MAX_PREDICTIONS:
                raise ValueError(f'{field} must be a bounded array')
            if field != 'predictions':
                data[field] = tuple(rows)
                continue
            checked = []
            for row in rows:
                if not isinstance(row, dict):
                    raise ValueError('prediction must be an object')
                item = dict(row)
                key = item.get('order_key')
                if key is not None:
                    if not isinstance(key, list | tuple) or len(key) > 16:
                        raise ValueError('order_key must be a bounded array')
                    item['order_key'] = tuple(key)
                checked.append(PredictionDoc.model_validate(item))
            data[field] = tuple(checked)
        return model.model_validate(data)
    except (ValidationError, ValueError, TypeError) as exc:
        raise C.ContractError(f'engine output invalid: {str(exc)[:300]}') from None


def validate_engine_output_document(document: dict) -> EngineOutputDoc:
    """Validate only the existing four-engine persisted-output vocabulary."""
    return _validate_output_document(document, EngineOutputDoc)


def validate_provider_output_document(document: dict) -> EngineOutputDoc:
    """Preserve existing in-memory unified evaluation with identical field/ranking validation."""
    return _validate_output_document(document, _InMemoryEngineOutputDoc)


def load_engine_output(data: bytes) -> EngineOutputDoc:
    try:
        if len(data) > MAX_OUTPUT_BYTES:
            raise ValueError('engine output exceeds 64 MiB')
        document = strict_json(data)
    except (ValueError, RecursionError) as exc:
        raise C.ContractError(f'engine output invalid: {str(exc)[:300]}') from None
    return validate_engine_output_document(document)


class OutputCredit(_Strict):
    """Exact retained content and owner metadata behind one successful report pair/engine reference."""
    pair_id: C.Ident
    engine: Engine
    report_sha256: C.Sha256
    output_sha256: C.Sha256
    older_sha256: C.Sha256
    newer_sha256: C.Sha256
    symbols: Literal['hidden', 'visible']
    version: str | None = Field(default=None, max_length=200)


class OutputCredits(_Strict):
    """Local completed-run integrity record; no signature or claim of historical unmarked-run credit."""
    contract: Literal['tier-r-output-credits/1']
    reports: tuple[C.TierRReport, ...] = Field(min_length=1, max_length=10_000)
    outputs: tuple[OutputCredit, ...] = Field(max_length=MAX_PREDICTIONS)


class OutputCompletion(_Strict):
    """Presence blocks credit; removal is the final successful completion transition."""
    contract: Literal['tier-r-output-completion/1']
    status: Literal['incomplete']


class EvaluationFailure(_Strict):
    """Uncredited diagnostic reference, never a completed output manifest."""
    contract: Literal['tier-r-evaluation-failure/1']
    status: Literal['failed']
    credited: Literal[False]
    report_file: Literal['uncredited-report.json']
    report_sha256: C.Sha256
    error: str = Field(max_length=1000)


def output_sha256(doc: dict) -> str:
    return hashlib.sha256(canonical_json(doc)).hexdigest()


SCHEMAS = ((EngineOutputDoc, OUTPUT_CONTRACT), (OutputCredits, CREDITS_CONTRACT),
           (OutputCompletion, COMPLETION_CONTRACT), (EvaluationFailure, FAILURE_CONTRACT))


def render() -> dict[str, str]:
    out = {}
    for model, ident in SCHEMAS:
        schema = model.model_json_schema()
        schema['$id'] = f'https://patchtrace.local/schemas/{ident}/{model.__name__}.json'
        schema['$schema'] = 'https://json-schema.org/draft/2020-12/schema'
        out[f'{model.__name__}.json'] = json.dumps(schema, indent=2, sort_keys=True) + '\n'
    return out


_A, _B = hashlib.sha256(b'report-example-older').hexdigest(), hashlib.sha256(b'report-example-newer').hexdigest()


def example_engine_output() -> dict:
    return {'contract': OUTPUT_CONTRACT, 'engine': 'rz-diff', 'version': '0.9.1', 'symbols': 'hidden',
            'older_sha256': _A, 'newer_sha256': _B, 'implicit_unchanged': False,
            'predictions': [
                {'old_rva': 0x1000, 'new_rva': 0x1000, 'changed': False, 'similarity_milli': 1000,
                 'old_name': 'fcn.180001000', 'new_name': 'fcn.180001000'},
                {'old_rva': 0x1010, 'new_rva': 0x1010, 'changed': True, 'similarity_milli': 874,
                 'old_name': None, 'new_name': None}],
            'old_only_rvas': [0x1040], 'new_only_rvas': [0x1050], 'ignored_unaddressed': 0}


def example_report() -> dict:
    """The real evaluator on hand-made SYNTHETIC engine output over the template labels: never live evidence."""
    from . import evaluate as E
    from .schemas import example_labels
    labels = C.load_labels(C.dump_json(example_labels()))
    out = E.EngineOutput(
        engine='rz-diff', status='ok', version='0.9.1',
        predictions=(E.Prediction(0x1000, 0x1000, False, 1000), E.Prediction(0x1010, 0x1010, True, 874),
                     E.Prediction(0x1020, 0x1030, True, 990)),
        old_only=frozenset({0x1040}), new_only=frozenset({0x1050}))
    provider = E.StaticProvider('rz-diff', {labels.pair_id: out})
    return E.evaluate([labels], [provider], symbols='hidden',
                      notes=('SYNTHETIC example: mocked engine output, not live evidence',))


def _invalid(base: dict, mutate: Callable[[dict], None], *, redigest: bool = False) -> dict:
    doc = copy.deepcopy(base)
    mutate(doc)
    if redigest:
        doc['report_sha256'] = digest(doc, 'report_sha256')
    return doc


def examples() -> dict[str, dict]:
    report, output = example_report(), example_engine_output()
    attention = copy.deepcopy(output)
    attention.update(engine='attention', version='constructed-control')
    for rank, prediction in enumerate(attention['predictions'], 1):
        prediction['order_key'] = [rank]
    return {
        'valid-report-synthetic.json': report,
        'valid-engine-output-rz-diff.json': output,
        'valid-engine-output-attention.json': attention,
        'invalid-report-metric-negative.json': _invalid(
            report, lambda d: d['strata']['authored']['rz-diff'].update(identity_tp=-1), redigest=True),
        'invalid-report-unknown-engine.json': _invalid(
            report, lambda d: d['engines'][0].update(engine='ida'), redigest=True),
        'invalid-engine-output-rva-range.json': _invalid(
            output, lambda d: d['predictions'][0].update(old_rva=2**32)),
        'invalid-engine-output-unknown-field.json': _invalid(output, lambda d: d.update(raw_stdout='[]')),
    }


def check_example(path: Path) -> tuple[bool, str]:
    kind = path.name.split('-')[1]
    try:
        {'report': C.load_report, 'engine': load_engine_output}[kind](path.read_bytes())
    except C.ContractError as exc:
        return False, str(exc)[:300]
    return True, 'ok'


def write_all(root: Path = OUT) -> list[Path]:
    root.mkdir(parents=True, exist_ok=True)
    written = []
    for name, text in render().items():
        (root / name).write_text(text, encoding='utf-8', newline='\n')
        written.append(root / name)
    folder = root / EXAMPLES
    folder.mkdir(exist_ok=True)
    for name, doc in examples().items():
        (folder / name).write_bytes(C.dump_json(doc))
        written.append(folder / name)
    return written


def main() -> int:
    for path in write_all():
        print(path.as_posix())
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
